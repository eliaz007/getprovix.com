export function securityPullRequestBody(summary: string, writes: CommitWrite[]): string {
  const files = writes.map((file: (typeof writes)[number]) => `- \`${file.filePath}\``).join("\n");
  return [
    "## Security fix",
    "",
    summary,
    "",
    "### Files in this pull request",
    files,
    "",
    "Review the diff before merging. Secret values are redacted and are not included in this commit.",
    "",
    "Generated by Provix.",
  ].join("\n");
}
