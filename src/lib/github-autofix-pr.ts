import { Octokit } from "@octokit/rest";
import type { FirewallAutofixPullRequestResponse } from "@/lib/firewall-contract";
import { planAutofix } from "@/lib/firewall-autofix";
import { toGitHubOwnerRepo } from "@/lib/github-repo-ref";
import { isFirewallSourcePath, readGitHubSourceFile } from "@/lib/github-source-file";

const MAX_CONTENT = 1_500_000;

type PrResult = {
  status: number;
  body: FirewallAutofixPullRequestResponse;
};

function githubToken(): string | null {
  const token = process.env.GITHUB_TOKEN?.trim();
  return token ? token : null;
}

function statusOf(error: unknown): number | null {
  if (!error || typeof error !== "object" || !("status" in error)) return null;
  return typeof error.status === "number" ? error.status : null;
}

function githubResponseMessage(error: unknown): string {
  if (error && typeof error === "object" && "response" in error) {
    const data = (error as { response?: { data?: { message?: unknown } } }).response?.data;
    if (typeof data?.message === "string" && data.message.trim()) return data.message.trim();
  }
  return error instanceof Error ? error.message : "Unknown GitHub error";
}

function failureMessage(error: unknown): string {
  const status = statusOf(error);
  const raw = error instanceof Error ? error.message : "";
  if (status === 401) {
    return "GITHUB_TOKEN was rejected. Use a token that can push to this repository.";
  }
  if (status === 403 && /rate limit/i.test(raw)) {
    return "GitHub rate limit reached. Wait and try again, or use a token with a higher limit.";
  }
  if (status === 403) {
    return "GITHUB_TOKEN cannot create a branch or pull request on this repository.";
  }
  if (status === 404) {
    return "GitHub could not find that repository or branch. The token may not have access.";
  }
  if (status === 422) {
    return "GitHub rejected the pull request. The branch may already exist, or the split did not change any files.";
  }
  return "The pull request could not be opened.";
}

function branchName(filePath: string): string {
  const slug = filePath
    .replace(/\.(tsx|ts|jsx|js)$/i, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48)
    .toLowerCase();
  return `provix/split-${slug || "module"}-${Date.now().toString(36)}`;
}

function pullRequestBody(filePath: string, summary: string, writes: Array<{ filePath: string }>): string {
  const files = writes.map((file) => `- \`${file.filePath}\``).join("\n");
  return [
    "## Architectural refactor",
    "",
    `Provix Architecture Firewall split \`${filePath}\` into separate modules and replaced that file with a barrel that re-exports them.`,
    "",
    summary,
    "",
    "### Files in this pull request",
    files,
    "",
    "The original declarations stay exported from the same path. Review the diff before merging.",
    "",
    "Generated by Provix.",
  ].join("\n");
}

export async function openAutofixPullRequest(repoInput: string, filePath: string): Promise<PrResult> {
  const token = githubToken();
  if (!token) {
    return {
      status: 401,
      body: {
        ok: false,
        message: "GITHUB_TOKEN is not set. Add a token with permission to push branches and open pull requests.",
      },
    };
  }

  const ownerRepo = toGitHubOwnerRepo(repoInput);
  const [owner, repo] = ownerRepo?.split("/") ?? [];
  if (!ownerRepo || !owner || !repo) {
    return { status: 400, body: { ok: false, message: "repoUrl must be a public GitHub URL or owner/repo." } };
  }
  const repoUrl = `https://github.com/${ownerRepo}`;
  if (!isFirewallSourcePath(filePath)) {
    return {
      status: 400,
      body: { ok: false, message: "filePath must be a TypeScript or JavaScript source file inside the repository." },
    };
  }

  const remote = await readGitHubSourceFile(repoUrl, filePath);
  if (!remote.ok) {
    return { status: remote.status, body: { ok: false, message: remote.message } };
  }
  if (remote.content.length > MAX_CONTENT) {
    return { status: 413, body: { ok: false, message: "File is too large to refactor in one pass." } };
  }

  const plan = planAutofix(filePath, remote.content);
  if (!plan.canOpenPullRequest || plan.writes.length < 2) {
    return {
      status: 422,
      body: { ok: false, message: "This file has no safe module split, so no pull request was opened." },
    };
  }

  const octokit = new Octokit({ auth: token, userAgent: "provix-architecture-firewall" });
  const branch = branchName(filePath);
  const title = `refactor: split ${filePath} into modules`;
  let createdBranch = false;

  try {
    const repository = await octokit.rest.repos.get({ owner, repo });
    const base = repository.data.default_branch;
    const ref = await octokit.rest.git.getRef({
      owner,
      repo,
      ref: `heads/${base}`,
    });
    const parent = await octokit.rest.git.getCommit({
      owner,
      repo,
      commit_sha: ref.data.object.sha,
    });
    const tree = await octokit.rest.git.createTree({
      owner,
      repo,
      base_tree: parent.data.tree.sha,
      tree: plan.writes.map((file) => ({
        path: file.filePath,
        mode: "100644" as const,
        type: "blob" as const,
        content: file.content,
      })),
    });
    const commit = await octokit.rest.git.createCommit({
      owner,
      repo,
      message: `${title}\n\n${plan.summary}`,
      tree: tree.data.sha,
      parents: [ref.data.object.sha],
    });
    await octokit.rest.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${branch}`,
      sha: commit.data.sha,
    });
    createdBranch = true;
    const pull = await octokit.rest.pulls.create({
      owner,
      repo,
      title,
      head: branch,
      base,
      body: pullRequestBody(filePath, plan.summary, plan.writes),
    });

    return {
      status: 201,
      body: {
        ok: true,
        message: `Opened pull request #${pull.data.number} on ${repoUrl}.`,
        url: pull.data.html_url,
        number: pull.data.number,
        title: pull.data.title,
        branch,
        base,
      },
    };
  } catch (error) {
    const status = statusOf(error);
    const message = failureMessage(error);
    if (status === 404) {
      const githubMessage = githubResponseMessage(error);
      console.log(
        `[autofix/pr] GitHub could not find repository or branch. owner=${owner} repo=${repo} message=${githubMessage}`
      );
    }
    return {
      status: status === 401 ? 401 : status === 403 || status === 404 || status === 422 ? status : 502,
      body: {
        ok: false,
        message: createdBranch
          ? `${message} Branch ${branch} was created, but the pull request was not opened.`
          : message,
        branch: createdBranch ? branch : undefined,
      },
    };
  }
}
